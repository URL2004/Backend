function transformStrengthBlock(mode, documentProfile = 'unknown', requestStrength = '') {
  const strength = requestStrength || (mode === 'polish' ? 'polish' : (mode === 'blog' ? 'basic' : 'advanced'));
  if (strength === 'polish') {
    return [
      '[요청 강도: 다듬기]',
      '비문, 띄어쓰기, 접속, 실제 중복, 말투 혼합만 고친다.',
      '새 주장·예시·경험·감정·문단·1인칭을 만들지 않는다.',
      '이미 자연스러운 청크는 그대로 둘 수 있으며, 문서 전체에서 실제 오류가 있는 곳만 수정한다.'
    ].join('\n');
  }
  if (strength === 'advanced') {
    return [
      '[요청 강도: 고급]',
      '고급은 기본보다 더 넓은 범위의 일반 문장을 실질적으로 재구성하고, 서버가 모든 문서의 의미·사실·구조를 정밀 검증하는 모드다.',
      '사실·수치·인용 검증과 구조 점검은 서버가 별도로 수행한다. 승인된 근거가 없으면 내용을 보강하지 않는다.',
      '다듬기처럼 조사·동의어만 바꾸지 않는다. 원문의 논리 순서와 구조를 보존하면서 대상 문장의 절 순서·연결·호흡을 기본보다 넓게 다시 구성한다.',
      '이미 자연스러운 문장은 남기되, 휴머나이징 대상 문장은 사람이 직접 다시 쓴 차이가 분명해야 한다.',
      `원문 문서 프로필=${documentProfile || 'unknown'}.`
    ].join('\n');
  }
  return [
    '[요청 강도: 기본]',
    '기본은 교정·다듬기가 아니라 눈에 띄는 실질 휴머나이징이다. 원문의 사실과 장르는 보존하면서 반복 상투어, 추상적인 어순, 기계적인 접속과 균일한 호흡을 다시 구성한다.',
    '띄어쓰기·쉼표·조사·단순 동의어만 바꾼 결과는 실패다. 대상 일반 문장은 절의 순서, 연결 방식, 문장 호흡 중 하나 이상이 분명히 달라져야 한다.',
    '모든 문장을 같은 폭으로 억지로 바꾸거나 분량을 늘리지는 않는다. 이미 자연스러운 문장은 남기고 휴머나이징 대상 문장은 충분히 고친다.',
    '제목·목록·질문·인용·사실의 역할과 순서는 유지한다.',
    `원문 문서 프로필은 ${documentProfile || 'unknown'}이다.`
  ].join('\n');
}

