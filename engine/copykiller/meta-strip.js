'use strict';
// [engine/copykiller/meta-strip.js] 구조 메타 누수 제거 (P0).
//   장르전환/재구성이 본문에 흘린 "소절 1.1.이", "2.2.와 2.3.은", "(소절 …의 표현을 빌리자면)" 등
//   소절 번호 참조를 자연스러운 표현("앞서"/"이 둘")으로 치환. 결정론·무API.
//   ※ 단일 선두 번호(헤딩일 수 있음)는 건드리지 않는다. "소절"+번호, 또는 "N.N.와 N.N." 이중참조만.

function stripSectionMeta(text) {
  let t = String(text || '');

  // 1) 소절 번호를 참조하는 괄호 삽입구 통째 제거: "(소절 1.1.의 표현을 그대로 빌리자면)"
  t = t.replace(/\s*\((?:앞서\s*)?소절\s*\d+(?:\.\d+)*\.?[^)]*\)/g, '');

  // 2) "소절 N(.N)* + 조사" → "앞서"(의 보존)
  t = t.replace(/소절\s*\d+(?:\.\d+)*\.?\s*(은|는|이|가|을|를|의|에서|에)?/g,
    (_m, j) => (j === '의' ? '앞서의' : '앞서'));

  // 3) 본문 속 이중 소절 참조: "2.2.와 2.3.은" → "이 둘은"
  //    ("N.N.와 N.N." 형태는 헤딩엔 없고 프로즈 참조에만 나타남 → 안전)
  t = t.replace(/\d+\.\d+\.?\s*(?:와|과)\s*\d+\.\d+\.?\s*(은|는|이|가|을|를)?/g,
    (_m, j) => '이 둘' + (j || ''));

  // 4) 잔여 이중 공백 정리
  t = t.replace(/[ \t]{2,}/g, ' ');
  return t;
}

module.exports = { stripSectionMeta };
