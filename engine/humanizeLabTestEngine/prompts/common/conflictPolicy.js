function conflictPolicy(ctx = {}) {
  return `
[규칙 충돌 시 우선순위]
1순위: 사실·보호표현 보존
- 기술명, 기업명, 나열 항목, 수치, 단계명, 장비명은 자연화보다 우선한다.
- A·B·C 형태의 나열은 임의로 압축하지 않는다.
- 보호 표현이 사라질 위험이 있으면 해당 문장은 원문 구조를 유지한다.

2순위: 장르 보존
- 현장 블로그는 짧은 문단과 소제목 리듬을 유지한다.
- 학술 과제는 과도한 구어체와 극적 표현을 넣지 않는다.
- 기술 보고서는 정보 설명의 정확성을 문체 변화보다 우선한다.
- 자기소개서는 사용자가 제공한 경험 안에서만 구체화한다.

3순위: 휴머나이징 강도
- 원문이 이미 자연스러우면 low 또는 low_plus로 처리한다.
- 추상 일반론이 많지만 근거가 없으면 억지 경험을 만들지 않는다.
- 고위험 정형문은 반복 구조와 비인칭 표현만 제한적으로 완화한다.
`.trim();
}

module.exports = { conflictPolicy };
