function build(ctx = {}) {
  return `
[입력 위험도: 정형 표면 신호 높음]
원문 보존만으로는 변화가 거의 없을 수 있다. 사실과 구조는 유지하되, 표면 문장만 더 분명하게 다듬는다.

규칙:
1. 같은 문장 구조, 같은 종결어미, "기능한다/드러난다/삼는다/이어진다" 같은 반복 종결은 일부 교체한다.
2. 비인칭·수동 표현이 많으면 원문에 이미 있는 주체를 살려 능동 문장으로 바꾼다.
3. 한 문장에 정보가 지나치게 압축된 곳은 원문 내용 안에서만 두 문장으로 나눈다.
4. 단정적인 요약 문장만 이어지면 일부 문단 끝을 다음 행동, 관찰, 한계, 연결 흐름으로 바꾼다.
5. 전체 문장을 새로 쓰지는 않는다. 문장 내부 수정과 문단별 1~2문장 수준의 리듬 조정을 우선한다.
6. 목표 수정 강도는 문장 표면 기준 약 25~40%다. 단 보호 표현, 인용, 참고문헌은 그대로 둔다.
`.trim();
}

module.exports = { build };
