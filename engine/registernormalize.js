// 안전: 종결어미(문장 끝)와 1인칭 대명사만 결정론으로 치환 — 새 사실·내용·분량은 건드리지 않는다. 확신 못 하는
//   어미는 그대로 둔다(부분 정규화 > 오변환). 변환 가능한 고빈도·명확 어미만 다룬다.

// 문장 끝(종결어미)만 — 뒤가 문장 종결부호/줄끝일 때만 치환(중간의 "하다고/한다고"는 보호).
const END = '(?=[.!?…」』”’\\)\\]]*(?:[.!?…\\n]|$))';

// 한다체 → 존댓말(hap) 종결 변환 (고빈도·명확 어미만)
